def get_custom_emoji_tag(emoji: str) -> str:
    """
    Returns HTML custom emoji tag for given standard emoji if available in NewsEmoji map.
    """
    emoji_clean = emoji.strip()
    if emoji_clean in NEWSEMOJI_MAP:
        cid = NEWSEMOJI_MAP[emoji_clean]
        return f'<tg-emoji custom_emoji_id="{cid}">{emoji}</tg-emoji>'
    return emoji

def apply_custom_emojis(text: str) -> str:
    """
    Replaces supported standard unicode emojis in HTML text with Telegram custom animated emojis.
    Does not alter existing <tg-emoji> or HTML tags.
    """
    if not text:
        return text

    sorted_emojis = sorted(NEWSEMOJI_MAP.keys(), key=len, reverse=True)
    
    for e in sorted_emojis:
        cid = NEWSEMOJI_MAP[e]
        replacement = f'<tg-emoji custom_emoji_id="{cid}">{e}</tg-emoji>'
        pattern = re.compile(rf'(?<!custom_emoji_id=")(?<!">){re.escape(e)}(?!\s*</tg-emoji>)')
        text = pattern.sub(replacement, text)
        
    return text
